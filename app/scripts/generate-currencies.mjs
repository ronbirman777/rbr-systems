/** Codes that must never appear (guards against an accidental edit above). */
const EXCLUDED = [
  "BOV", "CHE", "CHW", "CLF", "COU", "MXV", "USN", "UYI", "UYW",
  "XAU", "XAG", "XPD", "XPT",
  "XBA", "XBB", "XBC", "XBD", "XDR", "XSU", "XUA",
  "XTS", "XXX",
  "ANG", "HRK", "CUC", "SLL", "ZWL", "VEF", "MRO", "STD", "BYR", "LTL", "LVL",
];

/** Only used if this runtime's CLDR has no English name for a (new) code. */
const FALLBACK_NAMES = {
  VED: "Venezuelan Digital Bolívar",
  XCG: "Caribbean Guilder",
  ZWG: "Zimbabwe Gold",
};

const displayNames = new Intl.DisplayNames(["en"], { type: "currency" });

const problems = [];
for (const [code, minor] of Object.entries(MINOR_UNITS)) {
  if (!/^[A-Z]{3}$/.test(code)) problems.push(`${code}: not a three-letter code`);
  if (![0, 2, 3].includes(minor)) problems.push(`${code}: unexpected minor units ${minor}`);
  if (EXCLUDED.includes(code)) problems.push(`${code}: is on the exclusion list`);
}
if (problems.length) {
  console.error("Currency data is invalid:\n  " + problems.join("\n  "));
  process.exit(1);
}

function englishName(code) {
  const cldr = displayNames.of(code);
  if (cldr && cldr !== code) return cldr;
  if (FALLBACK_NAMES[code]) return FALLBACK_NAMES[code];
  problems.push(`${code}: no English name (add it to FALLBACK_NAMES)`);
  return code;
}

const rows = Object.keys(MINOR_UNITS)
  .sort()
  .map((code) => ({ code, name: englishName(code), minorUnits: MINOR_UNITS[code] }));

if (problems.length) {
  console.error("Currency data is invalid:\n  " + problems.join("\n  "));
  process.exit(1);
}

const file = `/**
 * ISO 4217 active currency codes - the single list every Studio currency
 * picker and validator reads. GENERATED by scripts/generate-currencies.mjs,
 * then committed as literals; edit the generator, never this file.
 *
 * \`code\` is what gets stored, never the name. \`name\` is the English CLDR
 * name, used as the fallback label; localized names are resolved at runtime
 * with Intl.DisplayNames (lib/currencies/index.ts). \`minorUnits\` is the
 * ISO 4217 number of decimal places (JPY 0, EUR 2, KWD 3).
 *
 * Coverage: ${rows.length} active codes. Funds, index units, precious metals,
 * testing codes and withdrawn codes are deliberately excluded (see the
 * generator's header). This is retreat-item pricing data only and has no
 * connection to InnerDweS billing (lib/billing).
 */
export type Currency = {
  /** ISO 4217 alphabetic code. The stored value. */
  code: string;
  /** English display name (CLDR). */
  name: string;
  /** ISO 4217 minor units (decimal places). */
  minorUnits: number;
};

/** Sorted by code. */
export const CURRENCIES: readonly Currency[] = [
${rows.map((r) => `  { code: ${JSON.stringify(r.code)}, name: ${JSON.stringify(r.name)}, minorUnits: ${r.minorUnits} },`).join("\n")}
] as const;
`;

if (process.argv.includes("--check")) {
  const current = readFileSync(OUT, "utf8");
  if (current !== file) {
    console.error("src/lib/currencies/data.ts is stale - run: node scripts/generate-currencies.mjs");
    process.exit(1);
  }
  console.log(`currency data up to date (${rows.length} codes)`);
} else {
  writeFileSync(OUT, file);
  console.log(`wrote ${rows.length} currencies to ${OUT}`);
}
