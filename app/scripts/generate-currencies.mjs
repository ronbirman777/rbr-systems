/**
 * Regenerates src/lib/currencies/data.ts.
 *
 *   node scripts/generate-currencies.mjs            # rewrite the dataset
 *   node scripts/generate-currencies.mjs --check    # fail if it is stale
 *
 * Same pattern as scripts/generate-countries.mjs: the source list is
 * embedded here (no dependency), English names come from CLDR via
 * Intl.DisplayNames at GENERATION time and are committed as literals, so
 * the running app never depends on the host's ICU for the stored list.
 *
 * MINOR_UNITS is the ISO 4217 "List One" of ACTIVE currency codes with
 * their ISO minor units (decimal places). ISO's minor units are the
 * authority here, not CLDR's display digits (they differ for a few codes).
 *
 * Deliberately excluded (not money a retreat item is priced in):
 *   - funds / index units: BOV, CHE, CHW, CLF, COU, MXV, USN, UYI, UYW
 *   - precious metals: XAU, XAG, XPD, XPT
 *   - bond-market units and SDR-like units: XBA, XBB, XBC, XBD, XDR, XSU, XUA
 *   - testing and "no currency": XTS, XXX
 *   - withdrawn codes: ANG (replaced by XCG, 2025), HRK, CUC, SLL, ZWL,
 *     VEF, MRO, STD, BYR, LTL, LVL and similar
 */
import { writeFileSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const OUT = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "lib", "currencies", "data.ts");

