-- TASK 032 addendum - payment confirmation, receipts and invoices.
--
-- ADDITIVE. Adds the payment/invoice ledger and the payment-confirmation email
-- template. Does not touch any existing table's data or any earlier function.
--
-- billing_invoices is a synchronised COPY of Stripe's invoice facts (ids,
-- status, amounts, period, and Stripe-HOSTED document URLs). Stripe remains
-- the official issuer/record of the document; InnerDweS stores only what it
-- needs to (a) show the customer their payment history and give them the
-- official document, (b) let Admin answer "I paid but didn't get my invoice",
-- and (c) decide - exactly once - when a payment confirmation email is due.
-- It never stores card numbers, CVC, bank details or raw payment-method data.
--
-- The legal ISSUER of the document (legal name/address, VAT/GST number,
-- numbering, whether it is legally an "invoice"/"tax invoice"/"receipt") is NOT
-- stored or hard-coded here: it is whatever Stripe renders from the account's
-- own configuration, and remains part of the Paid Launch legal/tax gate.
--
-- Never edit 0001-0039. Forward-only.

create table public.billing_invoices (
  id uuid primary key default gen_random_uuid(),
  stripe_mode text not null check (stripe_mode in ('test', 'live')),
  stripe_invoice_id text not null check (stripe_invoice_id ~ '^in_[A-Za-z0-9_]+$'),
  stripe_subscription_id text,
  stripe_customer_id text,
  space_subscription_id uuid references public.space_subscriptions(id) on delete set null,
  tenant_id uuid references public.tenants(id) on delete set null,
  -- The billing owner (account) the payment belongs to. SET NULL on account
  -- deletion (financial record retained, anonymised) like the other billing rows.
  user_id uuid references auth.users(id) on delete set null,
  coupon_redemption_id uuid references public.coupon_redemptions(id) on delete set null,
  status text not null check (status in ('draft', 'open', 'paid', 'void', 'uncollectible')),
  billing_reason text check (billing_reason is null or length(billing_reason) <= 60),
  currency char(3) not null check (currency = upper(currency)),
  subtotal_minor integer check (subtotal_minor is null or subtotal_minor >= 0),
  discount_minor integer not null default 0 check (discount_minor >= 0),
  tax_minor integer check (tax_minor is null or tax_minor >= 0),
  total_minor integer check (total_minor is null or total_minor >= 0),
  amount_due_minor integer check (amount_due_minor is null or amount_due_minor >= 0),
  amount_paid_minor integer not null default 0 check (amount_paid_minor >= 0),
  amount_refunded_minor integer not null default 0 check (amount_refunded_minor >= 0),
  -- Stripe's own invoice number, as issued (never generated by InnerDweS).
  invoice_number text,
  -- Stripe-hosted documents. hosted_invoice_url / invoice_pdf_url / receipt_url
  -- are what the customer is sent to for the OFFICIAL document.
  hosted_invoice_url text,
  invoice_pdf_url text,
  receipt_url text,
  period_start timestamptz,
  period_end timestamptz,
  issued_at timestamptz,
  paid_at timestamptz,
  failed_at timestamptz,
  attempt_count integer not null default 0 check (attempt_count >= 0),
  discount_applied boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (stripe_mode, stripe_invoice_id)
);
create index billing_invoices_subscription_idx on public.billing_invoices (space_subscription_id, issued_at desc);
create index billing_invoices_user_idx on public.billing_invoices (user_id, issued_at desc);
create index billing_invoices_tenant_idx on public.billing_invoices (tenant_id, issued_at desc);
create index billing_invoices_status_idx on public.billing_invoices (status, issued_at desc);

-- RLS intent: the BILLING OWNER (account) may SELECT their own payment history
-- (Billing/Plan page). No client insert/update/delete. Admin reads through the
-- service-role server code behind MFA, never through this policy.
alter table public.billing_invoices enable row level security;
revoke all on public.billing_invoices from public, anon, authenticated;
grant select on public.billing_invoices to authenticated;
create policy "billing_invoices: billing owner can select"
  on public.billing_invoices for select
  using (user_id = auth.uid());

-- The payment-confirmation email template joins the outbox allow-list.
alter table public.billing_email_outbox drop constraint billing_email_outbox_template_check;
alter table public.billing_email_outbox add constraint billing_email_outbox_template_check
  check (template in (
    'subscription_started', 'payment_confirmation', 'payment_failed', 'guest_unavailable',
    'studio_suspended', 'final_warning', 'cancellation_scheduled', 'subscription_ended',
    'payment_recovered'
  ));

-- ---------------------------------------------------------------------------
-- billing_upsert_invoice: idempotently record Stripe's CURRENT view of an
-- invoice. The webhook handler retrieves the invoice from Stripe and passes it
-- here, so duplicate delivery and out-of-order events converge on the same
-- row. Returns what changed so the caller can decide, exactly once, whether a
-- payment confirmation is due:
--   newly_paid   true ONLY on the transition into 'paid' (never on a replay)
--   newly_failed true ONLY on the first failure observation
-- Status never regresses: a paid invoice stays paid; a void invoice stays void.
-- Only server code with a verified Stripe object may call this.
-- ---------------------------------------------------------------------------
create function public.billing_upsert_invoice(p jsonb)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, pg_temp
as $$
declare
  v_existing public.billing_invoices;
  v_sub public.space_subscriptions;
  v_red public.coupon_redemptions;
  v_status text := p ->> 'status';
  v_effective text;
  v_newly_paid boolean := false;
  v_newly_failed boolean := false;
  v_id uuid;
  v_result text;
begin
  if v_status not in ('draft', 'open', 'paid', 'void', 'uncollectible') then
    raise exception 'unsupported invoice status %', v_status;
  end if;

  select * into v_sub from public.space_subscriptions
  where stripe_mode = p ->> 'stripe_mode' and stripe_subscription_id = p ->> 'stripe_subscription_id';
  if found then
    select * into v_red from public.coupon_redemptions
    where space_subscription_id = v_sub.id and status in ('redeemed', 'completed', 'canceled')
    order by redeemed_at desc nulls last limit 1;
  end if;

  select * into v_existing from public.billing_invoices
  where stripe_mode = p ->> 'stripe_mode' and stripe_invoice_id = p ->> 'stripe_invoice_id'
  for update;

  if found then
    v_effective := case
      when v_existing.status = 'paid' then 'paid'
      when v_existing.status = 'void' then 'void'
      else v_status end;
    v_newly_paid := (v_effective = 'paid' and v_existing.status <> 'paid');
    v_newly_failed := (v_existing.failed_at is null and nullif(p ->> 'failed_at', '') is not null and v_effective <> 'paid');

    update public.billing_invoices set
      status = v_effective,
      stripe_subscription_id = coalesce(p ->> 'stripe_subscription_id', stripe_subscription_id),
      stripe_customer_id = coalesce(p ->> 'stripe_customer_id', stripe_customer_id),
      space_subscription_id = coalesce(v_sub.id, space_subscription_id),
      tenant_id = coalesce(v_sub.tenant_id, tenant_id),
      user_id = coalesce(v_sub.billing_owner_user_id, user_id),
      coupon_redemption_id = coalesce(v_red.id, coupon_redemption_id),
      billing_reason = coalesce(p ->> 'billing_reason', billing_reason),
      subtotal_minor = coalesce((p ->> 'subtotal_minor')::integer, subtotal_minor),
      discount_minor = coalesce((p ->> 'discount_minor')::integer, discount_minor),
      tax_minor = coalesce((p ->> 'tax_minor')::integer, tax_minor),
      total_minor = coalesce((p ->> 'total_minor')::integer, total_minor),
      amount_due_minor = coalesce((p ->> 'amount_due_minor')::integer, amount_due_minor),
      amount_paid_minor = case when v_effective = 'paid' then coalesce((p ->> 'amount_paid_minor')::integer, amount_paid_minor) else amount_paid_minor end,
      invoice_number = coalesce(p ->> 'invoice_number', invoice_number),
      hosted_invoice_url = coalesce(p ->> 'hosted_invoice_url', hosted_invoice_url),
      invoice_pdf_url = coalesce(p ->> 'invoice_pdf_url', invoice_pdf_url),
      receipt_url = coalesce(p ->> 'receipt_url', receipt_url),
      period_start = coalesce(nullif(p ->> 'period_start', '')::timestamptz, period_start),
      period_end = coalesce(nullif(p ->> 'period_end', '')::timestamptz, period_end),
      issued_at = coalesce(issued_at, nullif(p ->> 'issued_at', '')::timestamptz),
      paid_at = case when v_effective = 'paid' then coalesce(paid_at, nullif(p ->> 'paid_at', '')::timestamptz, now()) else paid_at end,
      failed_at = coalesce(failed_at, nullif(p ->> 'failed_at', '')::timestamptz),
      attempt_count = greatest(attempt_count, coalesce((p ->> 'attempt_count')::integer, 0)),
      discount_applied = coalesce((p ->> 'discount_applied')::boolean, discount_applied),
      updated_at = now()
    where id = v_existing.id
    returning id into v_id;
    v_result := case when v_newly_paid or v_newly_failed or v_effective <> v_existing.status then 'updated' else 'unchanged' end;
  else
    v_effective := v_status;
    v_newly_paid := (v_status = 'paid');
    v_newly_failed := (nullif(p ->> 'failed_at', '') is not null and v_status <> 'paid');
    insert into public.billing_invoices (
      stripe_mode, stripe_invoice_id, stripe_subscription_id, stripe_customer_id,
      space_subscription_id, tenant_id, user_id, coupon_redemption_id, status, billing_reason,
      currency, subtotal_minor, discount_minor, tax_minor, total_minor, amount_due_minor,
      amount_paid_minor, invoice_number, hosted_invoice_url, invoice_pdf_url, receipt_url,
      period_start, period_end, issued_at, paid_at, failed_at, attempt_count, discount_applied
    ) values (
      p ->> 'stripe_mode', p ->> 'stripe_invoice_id', p ->> 'stripe_subscription_id', p ->> 'stripe_customer_id',
      v_sub.id, v_sub.tenant_id, v_sub.billing_owner_user_id, v_red.id, v_status, p ->> 'billing_reason',
      upper(p ->> 'currency'), (p ->> 'subtotal_minor')::integer, coalesce((p ->> 'discount_minor')::integer, 0),
      (p ->> 'tax_minor')::integer, (p ->> 'total_minor')::integer, (p ->> 'amount_due_minor')::integer,
      case when v_status = 'paid' then coalesce((p ->> 'amount_paid_minor')::integer, 0) else 0 end,
      p ->> 'invoice_number', p ->> 'hosted_invoice_url', p ->> 'invoice_pdf_url', p ->> 'receipt_url',
      nullif(p ->> 'period_start', '')::timestamptz, nullif(p ->> 'period_end', '')::timestamptz,
      nullif(p ->> 'issued_at', '')::timestamptz,
      case when v_status = 'paid' then coalesce(nullif(p ->> 'paid_at', '')::timestamptz, now()) else null end,
      nullif(p ->> 'failed_at', '')::timestamptz, coalesce((p ->> 'attempt_count')::integer, 0),
      coalesce((p ->> 'discount_applied')::boolean, false)
    )
    returning id into v_id;
    v_result := 'created';
  end if;

  return jsonb_build_object(
    'result', v_result, 'invoice_id', v_id, 'status', v_effective,
    'newly_paid', v_newly_paid, 'newly_failed', v_newly_failed,
    'tenant_id', v_sub.tenant_id, 'subscription_id', v_sub.id, 'user_id', v_sub.billing_owner_user_id
  );
end;
$$;
revoke all on function public.billing_upsert_invoice(jsonb) from public, anon, authenticated;
grant execute on function public.billing_upsert_invoice(jsonb) to service_role;

-- Refund visibility (Stripe is authoritative; this only mirrors the amount so
-- support can see it). Idempotent: sets the absolute refunded amount.
create function public.billing_set_invoice_refund(p_mode text, p_invoice_id text, p_refunded_minor integer)
returns boolean
language plpgsql
security definer
set search_path = pg_catalog, pg_temp
as $$
declare
  v_n integer;
begin
  update public.billing_invoices
  set amount_refunded_minor = greatest(0, p_refunded_minor), updated_at = now()
  where stripe_mode = p_mode and stripe_invoice_id = p_invoice_id
    and amount_refunded_minor is distinct from greatest(0, p_refunded_minor);
  get diagnostics v_n = row_count;
  return v_n > 0;
end;
$$;
revoke all on function public.billing_set_invoice_refund(text, text, integer) from public, anon, authenticated;
grant execute on function public.billing_set_invoice_refund(text, text, integer) to service_role;
